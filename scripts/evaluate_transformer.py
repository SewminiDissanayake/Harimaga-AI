"""
evaluate_transformer.py
-----------------------
Compares the deployed char TF-IDF model with a multilingual transformer
(sentence embeddings + logistic regression) on exactly the same data.

LaBSE (Language-agnostic BERT Sentence Embedding, Google) was trained on 109
languages including Sinhala and Tamil, so it can understand meaning, not just
spelling. The question this script answers: is that worth a 1.8 GB model?

Run it on your own computer (it downloads the model the first time):

    pip install -r requirements-ml.txt
    python scripts/evaluate_transformer.py
    python scripts/evaluate_transformer.py --model sentence-transformers/paraphrase-multilingual-MiniLM-L12-v2

Results: reports/transformer_comparison.md
Note: this compares ML models only (no keyword/safety rules), so the numbers
are lower than the full system's in model_evaluation.md.
"""
from __future__ import annotations

import argparse
import time
import warnings
from pathlib import Path

import numpy as np
import pandas as pd

warnings.filterwarnings("ignore")

from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, f1_score
from sklearn.model_selection import RepeatedStratifiedKFold
from sklearn.pipeline import Pipeline

ROOT = Path(__file__).resolve().parents[1]
TRAIN_FILES = [
    ROOT / "data" / "training" / "harimaga_issue_training_v1.csv",
    ROOT / "data" / "training" / "harimaga_issue_training_v2_additions.csv",
]
DEV = ROOT / "data" / "eval" / "harimaga_challenge_v1.csv"
TEST = ROOT / "data" / "eval" / "harimaga_test_v2_sealed.csv"
OUT = ROOT / "reports" / "transformer_comparison.md"


def load_train():
    frames = [pd.read_csv(f, encoding="utf-8-sig") for f in TRAIN_FILES if f.exists()]
    return pd.concat(frames, ignore_index=True)


def tfidf_model():
    return Pipeline([
        ("v", TfidfVectorizer(analyzer="char_wb", ngram_range=(3, 5), sublinear_tf=True)),
        ("c", LogisticRegression(C=30, max_iter=5000, class_weight="balanced", random_state=42)),
    ])


class EmbeddingModel:
    """Sentence embeddings (computed once) + logistic regression on top."""

    def __init__(self, encode):
        self.encode = encode
        self.clf = LogisticRegression(C=10, max_iter=5000, class_weight="balanced", random_state=42)

    def fit(self, texts, labels):
        self.clf.fit(self.encode(list(texts)), labels)
        return self

    def predict(self, texts):
        return self.clf.predict(self.encode(list(texts)))


def make_encoder(model_name):
    from sentence_transformers import SentenceTransformer

    print(f"Loading {model_name} (first run downloads it)…")
    st = SentenceTransformer(model_name)
    cache = {}

    def encode(texts):
        missing = [t for t in dict.fromkeys(texts) if t not in cache]
        if missing:
            vecs = st.encode(missing, batch_size=32, normalize_embeddings=True, show_progress_bar=False)
            cache.update(zip(missing, vecs))
        return np.vstack([cache[t] for t in texts])

    return encode


def evaluate(name, make_model, train, dev, test):
    cv = RepeatedStratifiedKFold(n_splits=5, n_repeats=3, random_state=42)
    X, y = train.text.values, train.label.values
    f1s = []
    for tr, te in cv.split(X, y):
        m = make_model().fit(X[tr], y[tr])
        f1s.append(f1_score(y[te], m.predict(X[te]), average="macro"))

    t0 = time.perf_counter()
    m = make_model().fit(X, y)
    fit_seconds = time.perf_counter() - t0
    row = {"model": name, "cv_macro_f1": np.mean(f1s), "cv_std": np.std(f1s), "fit_seconds": fit_seconds}
    for split, df in [("dev", dev), ("test", test)]:
        pred = m.predict(df.text.values)
        row[f"{split}_acc"] = accuracy_score(df.label, pred)
        row[f"{split}_macro_f1"] = f1_score(df.label, pred, average="macro")
        for lang in ["en", "si", "singlish", "ta"]:
            mask = (df.language == lang).values
            row[f"{split}_{lang}"] = accuracy_score(df.label.values[mask], pred[mask])
    return row


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default="sentence-transformers/LaBSE")
    args = ap.parse_args()

    train, dev, test = load_train(), pd.read_csv(DEV), pd.read_csv(TEST)
    encode = make_encoder(args.model)

    rows = [
        evaluate("Char TF-IDF + LogReg (deployed)", tfidf_model, train, dev, test),
        evaluate(f"{args.model.split('/')[-1]} + LogReg", lambda: EmbeddingModel(encode), train, dev, test),
    ]
    df = pd.DataFrame(rows)

    pct = lambda x: f"{100 * x:.1f}%"
    lines = [
        "# Transformer vs TF-IDF (ML models only, no rules)",
        "",
        f"_Generated by `scripts/evaluate_transformer.py --model {args.model}`._",
        "",
        "| Model | CV macro-F1 | Dev acc. | **Test acc.** | Test macro-F1 | Test Sinhala | Test Singlish | Test Tamil |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for _, r in df.iterrows():
        lines.append(
            f"| {r.model} | {r.cv_macro_f1:.3f} ± {r.cv_std:.3f} | {pct(r.dev_acc)} | **{pct(r.test_acc)}** | "
            f"{r.test_macro_f1:.3f} | {pct(r.test_si)} | {pct(r.test_singlish)} | {pct(r.test_ta)} |"
        )
    lines += [
        "",
        "Things to weigh besides accuracy: model size (LaBSE ≈ 1.8 GB vs a few MB), memory and speed on a "
        "small server, and whether the gain holds on real user data.",
        "",
    ]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    pd.set_option("display.width", 200)
    print(df.round(3).to_string(index=False))
    print(f"\nSaved {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
